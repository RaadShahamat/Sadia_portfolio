#!/usr/bin/env node
/* =====================================================================
   Photo list builder
   ---------------------------------------------------------------------
   Looks inside the /images folder and writes assets/js/photos.js —
   a list of every photo in every folder. The website reads that list,
   so adding or removing photos never needs a code change.

   It runs automatically on GitHub every time you upload changes.
   To preview photos on your own computer, run:   node tools/build-photos.mjs
   ===================================================================== */
import { readdirSync, writeFileSync } from "node:fs";
import { join, relative, sep, extname, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const IMAGES = join(ROOT, "images");
const OUT = join(ROOT, "assets", "js", "photos.js");
const EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"]);
const byName = new Intl.Collator("en", { numeric: true, sensitivity: "base" }).compare;
const SMALL = new Set(["a", "an", "and", "at", "by", "for", "in", "of", "on", "the", "to", "with"]);

/* "02-mount-rainier_washington.jpg" -> "Mount Rainier, Washington"
   "IMG_2034.jpg" or "cover.jpg"      -> ""  (no caption)            */
function caption(file) {
  let base = file.replace(/\.[^.]+$/, "").replace(/^\d+[-_. ]+/, "").trim();
  if (!base || /^cover$/i.test(base) || /^\d+$/.test(base)) return "";
  if (/^(img|dsc|dscn|dscf|pxl|photo|image|screenshot|whatsapp|signal|wp|mvimg)[-_ ]?\d/i.test(base)) return "";
  return base.split("_").map((part) =>
    part.split(/[-\s]+/).filter(Boolean).map((w, i) =>
      i > 0 && SMALL.has(w.toLowerCase()) ? w.toLowerCase() : w.charAt(0).toUpperCase() + w.slice(1)
    ).join(" ")
  ).filter(Boolean).join(", ");
}

const photos = {};
let count = 0;

function walk(dir) {
  let entries;
  try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return; }
  const files = [];
  for (const e of entries) {
    if (e.name.startsWith(".")) continue;
    if (e.isDirectory()) walk(join(dir, e.name));
    else if (EXT.has(extname(e.name).toLowerCase())) files.push(e.name);
  }
  const key = relative(IMAGES, dir).split(sep).join("/");
  if (!key || !files.length) return;
  files.sort(byName);
  photos[key] = files.map((f) => ({
    src: ["images", ...key.split("/"), f].map(encodeURIComponent).join("/"),
    file: f,
    caption: caption(f)
  }));
  count += files.length;
}

walk(IMAGES);

const sorted = Object.fromEntries(Object.keys(photos).sort(byName).map((k) => [k, photos[k]]));
writeFileSync(OUT,
  "/* AUTO-GENERATED by tools/build-photos.mjs — do not edit by hand.\n" +
  "   It lists the photos found in each folder inside /images. */\n" +
  "window.PHOTOS = " + JSON.stringify(sorted, null, 2) + ";\n");

console.log(`Found ${count} photo(s) in ${Object.keys(sorted).length} folder(s):`);
for (const [k, v] of Object.entries(sorted)) console.log(`  images/${k}: ${v.length}`);
